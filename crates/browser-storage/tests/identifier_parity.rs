//! 2000 adversarial identifiers, hashed by CPython and by this crate — and 120
//! of them used as real primary keys in a database the reference implementation wrote.
//!
//! `identifier_hash` is `StorageSystemMixin._get_hash`, the helper the reference implementation
//! documents for third-party backends:
//!
//! ```python
//! _identifier = identifier.lower().strip()
//! _identifier_bytes = _identifier.encode("utf-8")
//! return f"{sha256(_identifier_bytes).hexdigest()}_{len(_identifier_bytes)}"
//! ```
//!
//! Three ways to get it wrong, all of them exercised here:
//!
//! * **order** — `.lower()` runs *before* `.strip()`, and the two do not
//!   commute for every input;
//! * **whitespace set** — `str.strip()` removes Unicode `White_Space` *plus*
//!   `U+001C..U+001F`, four code points [`str::trim`] leaves alone, while
//!   leaving `U+200B` and `U+FEFF` — which look like spaces and are not — in
//!   place;
//! * **length suffix** — it counts UTF-8 *bytes* of the folded string, so
//!   `İ` (2 bytes) becomes `i̇` (3 bytes) and the suffix changes with it.
//!
//! `testdata/python_identifiers.jsonl` is generated by
//! `tools/gen_identifier_corpus.py`: every whitespace code point Python knows,
//! every interesting casing (`İ`, `ẞ`, `Σ`, titlecase digraphs, fullwidth
//! letters, Roman numerals), NULs, emoji, combining marks, 200-character runs
//! and 2000 seeded random combinations of all of it.
//!
//! `testdata/python_identifiers.db` then keys 120 of the nastiest at the *row*
//! level, because a digest that matches is worth nothing if the identifier
//! cannot survive the `WHERE identifier = ?` lookup that actually finds the
//! row.

mod common;

use std::fs;
use std::path::PathBuf;

use browser_storage::hash::identifier_hash;
use browser_storage::python_json;
use browser_storage::r#trait::StorageSystem;
use browser_storage::sqlite::SqliteStorage;

use common::TempDb;

fn testdata(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("testdata")
        .join(name)
}

fn lines(name: &str) -> Vec<serde_json::Value> {
    let path = testdata(name);
    let text =
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    text.lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| serde_json::from_str(line).unwrap_or_else(|e| panic!("bad line: {e}")))
        .collect()
}

/// Every one of the 2000 digests matches CPython's.
#[test]
fn identifier_hash_matches_get_hash_on_two_thousand_identifiers() {
    let cases = lines("python_identifiers.jsonl");
    assert_eq!(cases.len(), 2000, "the corpus lost rows");

    let mut mismatches = Vec::new();
    for case in &cases {
        let identifier = case["identifier"].as_str().expect("identifier");
        let expected = case["hash"].as_str().expect("hash");
        let actual = identifier_hash(identifier);
        if actual != expected {
            mismatches.push(format!(
                "{identifier:?}\n     rust: {actual}\n   python: {expected}"
            ));
        }
    }

    assert!(
        mismatches.is_empty(),
        "{} of {} identifiers hash differently:\n  {}",
        mismatches.len(),
        cases.len(),
        mismatches
            .iter()
            .take(20)
            .cloned()
            .collect::<Vec<_>>()
            .join("\n  "),
    );
}

/// The digest's byte-length suffix is the length CPython measured.
///
/// A digest can only match if the folded bytes matched, so this is redundant in
/// principle — but when it *does* fail it says immediately whether the case
/// fold or the trim is at fault, which the digest alone cannot.
#[test]
fn the_length_suffix_is_pythons_post_fold_byte_count() {
    for case in lines("python_identifiers.jsonl") {
        let identifier = case["identifier"].as_str().expect("identifier");
        let stripped = case["stripped"].as_str().expect("stripped");

        let hashed = identifier_hash(identifier);
        let (_, suffix) = hashed.rsplit_once('_').expect("the length suffix");
        assert_eq!(
            suffix,
            stripped.len().to_string(),
            "{identifier:?} folded to {stripped:?}",
        );
    }
}

/// The corpus really does contain the cases it claims to.
///
/// Without this a future edit could shrink the interesting part of the corpus
/// to nothing and the parity test above would still pass.
#[test]
fn the_corpus_covers_the_hard_cases() {
    let cases = lines("python_identifiers.jsonl");
    let identifiers: Vec<&str> = cases
        .iter()
        .map(|case| case["identifier"].as_str().expect("identifier"))
        .collect();

    let contains = |needle: &str| identifiers.iter().any(|id| id.contains(needle));

    // Python-only whitespace.
    for c in ['\u{1c}', '\u{1d}', '\u{1e}', '\u{1f}', '\u{85}'] {
        assert!(contains(&c.to_string()), "missing {c:?}");
    }
    // Look-alikes that are *not* whitespace.
    for c in ['\u{200b}', '\u{feff}'] {
        assert!(contains(&c.to_string()), "missing {c:?}");
    }
    // Casing that changes length, and casing that does not round-trip.
    for s in ["\u{130}", "\u{1e9e}", "\u{3a3}", "\u{1c5}", "\u{ff21}"] {
        assert!(contains(s), "missing {s:?}");
    }
    // Bytes that break naive SQL and JSON handling.
    for s in ["\0", "\"", "\\", "\u{1f600}"] {
        assert!(contains(s), "missing {s:?}");
    }
}

/// Copies the Python-written fixture somewhere writable.
fn python_database(label: &str) -> TempDb {
    let db = TempDb::new(label);
    let fixture = testdata("python_identifiers.db");
    fs::copy(&fixture, db.path())
        .unwrap_or_else(|e| panic!("cannot copy {}: {e}", fixture.display()));
    db
}

/// Every row Python keyed by a nasty identifier is found by that same string.
///
/// NULs, newlines, 200-character runs, emoji, combining marks and leading or
/// trailing whitespace all have to survive binding, storage and the
/// `WHERE identifier = ?` comparison unchanged — the identifier is stored
/// *raw*, never hashed and never trimmed, exactly as Python stores it.
#[test]
fn every_awkward_identifier_finds_its_row() {
    let db = python_database("identifiers");
    let storage = SqliteStorage::open(db.path(), Some("https://identifiers.example.com"))
        .unwrap_or_else(|e| panic!("open: {e}"));
    // `identifiers.example.com` is a subdomain, so the namespace is the
    // registrable domain — the same one Python derived when it wrote the file.
    assert_eq!(storage.base_url(), "example.com");

    let rows = lines("python_identifiers_rows.jsonl");
    assert_eq!(rows.len(), 120);

    for row in &rows {
        let identifier = row["identifier"].as_str().expect("identifier");
        assert_eq!(
            row["base_url"].as_str(),
            Some(storage.base_url()),
            "{identifier:?}",
        );

        let stored = storage
            .retrieve(identifier)
            .unwrap_or_else(|e| panic!("retrieve {identifier:?}: {e}"))
            .unwrap_or_else(|| panic!("no row for {identifier:?}"));

        let encoded = python_json::to_string(&stored).expect("encode");
        assert_eq!(
            encoded,
            row["element_data"].as_str().expect("element_data"),
            "{identifier:?}",
        );
    }

    // A near-miss must *not* match: the identifier is compared byte for byte,
    // so trimming or case-folding it would silently merge two rows. (Some
    // trimmed forms are themselves identifiers in the corpus — those rows exist
    // on their own account and are skipped.)
    let stored_identifiers: std::collections::HashSet<&str> = rows
        .iter()
        .map(|row| row["identifier"].as_str().expect("identifier"))
        .collect();
    for row in &rows {
        let identifier = row["identifier"].as_str().expect("identifier");
        for variant in [identifier.trim(), &identifier.to_uppercase()] {
            if variant != identifier && !variant.is_empty() && !stored_identifiers.contains(variant)
            {
                assert!(
                    storage.retrieve(variant).expect("retrieve").is_none(),
                    "{identifier:?} was also found as {variant:?}",
                );
            }
        }
    }
}

/// Writing those identifiers back keeps them byte-identical.
#[test]
fn awkward_identifiers_survive_a_write_from_this_crate() {
    let source = python_database("identifiers-mirror");
    let target = TempDb::new("identifiers-target");

    let from_python = SqliteStorage::open(source.path(), Some("https://identifiers.example.com"))
        .unwrap_or_else(|e| panic!("open source: {e}"));
    let from_rust = SqliteStorage::open(target.path(), Some("https://identifiers.example.com"))
        .unwrap_or_else(|e| panic!("open target: {e}"));

    let rows = lines("python_identifiers_rows.jsonl");
    for row in &rows {
        let identifier = row["identifier"].as_str().expect("identifier");
        let fingerprint = from_python
            .retrieve(identifier)
            .expect("retrieve")
            .unwrap_or_else(|| panic!("no row for {identifier:?}"));
        from_rust.save(&fingerprint, identifier).expect("save");
    }

    assert_eq!(from_rust.len().expect("len"), rows.len() as i64);
    for row in &rows {
        let identifier = row["identifier"].as_str().expect("identifier");
        assert!(
            from_rust.retrieve(identifier).expect("retrieve").is_some(),
            "{identifier:?} did not come back",
        );
    }
}
