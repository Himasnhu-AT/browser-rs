//! Build script for `browser-core`.
//!
//! Turns `assets/html4_entities.txt` into a `phf::Map<&'static str, u32>` of HTML4
//! named character references, written to `$OUT_DIR/html4_entities.rs` and included
//! by `src/entities.rs`.
//!
//! The asset is a verbatim dump of CPython's `html.entities.name2codepoint` (the
//! HTML4 set, 252 names). `w3lib.html.replace_entities` resolves named references
//! against exactly that table — **not** the HTML5 table — so the port must use the
//! same data or it will decode `&apos;` (HTML5-only) and friends differently.

use std::env;
use std::fs;
use std::io::{BufWriter, Write};
use std::path::Path;

fn main() {
    println!("cargo::rerun-if-changed=assets/html4_entities.txt");
    println!("cargo::rerun-if-changed=build.rs");

    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set");
    let asset = Path::new(&manifest_dir).join("assets/html4_entities.txt");
    let text = fs::read_to_string(&asset)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", asset.display()));

    let mut map = phf_codegen::Map::new();
    let mut count = 0usize;
    for (lineno, line) in text.lines().enumerate() {
        let line = line.trim_end_matches(['\r', '\n']);
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (name, codepoint) = line.split_once('\t').unwrap_or_else(|| {
            panic!(
                "{}:{}: expected `name<TAB>codepoint`, got {line:?}",
                asset.display(),
                lineno + 1
            )
        });
        let codepoint: u32 = codepoint.trim().parse().unwrap_or_else(|e| {
            panic!(
                "{}:{}: bad codepoint {codepoint:?}: {e}",
                asset.display(),
                lineno + 1
            )
        });
        map.entry(name, format!("{codepoint}u32"));
        count += 1;
    }
    assert!(count > 0, "html4_entities.txt produced no entries");

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is always set");
    let dest = Path::new(&out_dir).join("html4_entities.rs");
    let file = fs::File::create(&dest)
        .unwrap_or_else(|e| panic!("failed to create {}: {e}", dest.display()));
    let mut out = BufWriter::new(file);

    writeln!(
        out,
        "/// HTML4 named character references (`html.entities.name2codepoint`), \
         generated by `build.rs`."
    )
    .expect("write to OUT_DIR failed");
    writeln!(
        out,
        "pub static HTML4_ENTITIES: phf::Map<&'static str, u32> = {};",
        map.build()
    )
    .expect("write to OUT_DIR failed");
    writeln!(
        out,
        "/// Number of entries in [`HTML4_ENTITIES`]; pinned by a unit test."
    )
    .expect("write to OUT_DIR failed");
    writeln!(out, "pub const HTML4_ENTITY_COUNT: usize = {count};")
        .expect("write to OUT_DIR failed");
    out.flush().expect("flush of OUT_DIR file failed");
}
